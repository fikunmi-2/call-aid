"""Regenerate shared contracts/fixtures: uv run python export_contract.py."""

import json
from pathlib import Path

from intake import IntakeWorkflow
from intake_schema import LABELS, VALUES, Fact, PublishedSBARReport, SBARReport
from sbar import generate_sbar

root = Path(__file__).resolve().parent.parent
directory = root / "contracts"
(directory / "fixtures").mkdir(parents=True, exist_ok=True)
(directory / "sbar.schema.json").write_text(
    json.dumps(SBARReport.model_json_schema(), indent=2) + "\n", encoding="utf-8"
)
(directory / "published-sbar.schema.json").write_text(
    json.dumps(PublishedSBARReport.model_json_schema(), indent=2) + "\n",
    encoding="utf-8",
)
(root / "web/lib/intake-values.ts").write_text(
    "// Generated by agent/export_contract.py. Do not edit.\nexport const intakeValues = "
    + json.dumps(VALUES, indent=2)
    + " as const;\nexport const intakeLabels = "
    + json.dumps(LABELS, indent=2)
    + " as const;\n",
    encoding="utf-8",
)
workflow = IntakeWorkflow()
workflow.case_id = "a0000000-0000-4000-8000-000000000002"
workflow.started_on = "2026-11-08"
workflow.finish_incomplete()
payload = generate_sbar(workflow).model_dump(mode="json")
payload["generated_on"] = "2026-11-08"
(directory / "fixtures/incomplete.json").write_text(
    json.dumps(payload, indent=2) + "\n", encoding="utf-8"
)
workflow = IntakeWorkflow()
workflow.case_id = "b0000000-0000-4000-8000-000000000002"
workflow.started_on = "2026-11-08"
for key, values in {
    "chief_complaint": ["headache"],
    "onset": ["today"],
    "duration": ["intermittent"],
    "progression": ["worsening"],
    "severity": ["severe"],
    "onset_pattern": ["sudden"],
    "associated_symptoms": ["light_sensitivity"],
    "background": ["no_similar_episode"],
}.items():
    workflow.facts[key] = Fact(field=key, state="reported", values=values)
workflow.phase = "completed"
workflow.reviewed = True
payload = generate_sbar(workflow).model_dump(mode="json")
payload["generated_on"] = "2026-11-08"
(directory / "fixtures/completed.json").write_text(
    json.dumps(payload, indent=2) + "\n", encoding="utf-8"
)
payload.update(
    schema_version="3.0",
    publication="published",
    publication_policy_version="public-1.0",
)
payload["recommendation"]["record_saved"] = True
payload["recommendation"]["actions"].append("record_saved")
payload["recommendation"]["text"] = (
    "The prototype generated and saved this demonstration report. The caller reviewed it. No clinical recommendation was made."
)
published = PublishedSBARReport.model_validate(payload)
(directory / "fixtures/published.json").write_text(
    published.model_dump_json(indent=2) + "\n", encoding="utf-8"
)
